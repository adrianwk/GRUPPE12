void setup() {
  Serial.begin(9600);

  if (!display.begin(SSD1306_SWITCHCAPVCC, SCREEN_ADDRESS)) { // Hvis skjermen er 3.3V men får 5V. Ikke begynn tror jeg?
    Serial.println(F("SSD1306 allocation failed"));
    for (;;);  // Halt
  }

  display.clearDisplay();

  // Center the bitmap on the screen
  int x = (SCREEN_WIDTH  - IMG_WIDTH)  / 2;
  int y = (SCREEN_HEIGHT - IMG_HEIGHT) / 2;

  display.drawBitmap(x, y, myBitmap, IMG_WIDTH, IMG_HEIGHT, SSD1306_WHITE);
  display.display();   // Push the buffer to the screen
}

